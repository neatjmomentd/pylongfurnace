#include <string>
#include <vector>

void count_zeros() {
    int n = 102030;
    int zeros = 0;
    while (n > 0) { if (n % 10 == 0) zeros += 1; n /= 10; }
    (void)zeros;
}

void min_of_two() {
    int a = 33, b = 57;
    int m = (a < b) ? a : b;
    (void)m;
}

void greatest_divisor() {
    int a = 48, b = 18;
    while (b != 0) {
        int t = a % b;
        a = b;
        b = t;
    }
    (void)a;
}

void fibonacci_sum() {
    int f0 = 0, f1 = 1;
    int acc = 0;
    for (int i = 0; i < 10; ++i) {
        acc += f0;
        int next = f0 + f1;
        f0 = f1;
        f1 = next;
    }
    (void)acc;
}

